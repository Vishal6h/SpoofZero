def row(i=0, label=0, source="a", role="train", reality="REAL", **kwargs):
    word = "item" + chr(97 + i // 26 % 26) + chr(97 + i % 26)
    body = ("meeting agenda colleague report team" if label == 0 else "urgent account password verify suspended") + " " + word
    defaults = dict(source=source, source_id=str(i), label=label, body=body,
                    role=role, reality=reality, date_start="2020-01-01", date_end="2020-01-01",
                    date_quality="DOCUMENTED_MESSAGE_DATE")
    defaults.update(kwargs)
    return data.normalize_example(defaults)

def batch(count=80, offset=0, **kwargs):
    return [row(i+offset, i % 2, **kwargs) for i in range(count)]

def perfect_evaluation():
    rows = batch(200, role="test")
    return evaluate_records(rows, [r["label"] * .98 + .01 for r in rows], .5)

def perfect_evidence():
    return {"modern_real_email_phishing":100, "synthetic_malicious_fraction":0.,
            "unknown_malicious_fraction":0., "external_real_email_counts":{"0":100,"1":100}}

