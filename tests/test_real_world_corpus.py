class LockedExperimentTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp=TemporaryDirectory()
        cls.base=Path(cls.temp.name);cls.dataset=cls.base/"data";cls.dataset.mkdir()
        parts={"train":batch(80), "validation":batch(60,offset=100,role="validation",date_start="2023-04-01",date_end="2023-04-01"),
               "validation_historical":batch(20,offset=200,role="validation_historical"),
               "test":batch(40,offset=300,role="test",date_start="2024-06-01",date_end="2024-06-01"),
               "external":batch(40,offset=400,source="smishx",role="external",channel="sms"),
               "date_unknown":[],"synthetic_stress":[]}
        cls.manifest={"splits":{},"recipe":{"transfer_pairs":[],
            "evidence":{"independent_real_both_class_sources":0,"representative_external_holdout":False}}}
        for name,rows in parts.items():
            p=cls.dataset/(name+".jsonl")
            p.write_text("".join(json.dumps(r)+"\n" for r in rows))
            cls.manifest["splits"][name]={"sha256":digest(p.read_bytes())}
        write_json(cls.dataset/"manifest.json",cls.manifest)
        cls.run_dir=cls.base/"run";cls.lock=cls.base/"selection.json"
        m=perfect_evaluation()
        source_tests={"summary":m["source_summary"],"all_folds_evaluated":True,
                      "paired_source_transfer":[{"status":"EVALUATED","evaluation":m}]}
        reads=[]
        real_reader=evaluate.checked_rows
        def reader(dataset,part,manifest):
            reads.append(part)
            if part in {"test","external","date_unknown","synthetic_stress"}:
                raise AssertionError("Selection opened held-out corpus")
            return real_reader(dataset,part,manifest)
        with patch.object(evaluate,"checked_rows",side_effect=reader),patch.object(evaluate,"source_evaluation",return_value=source_tests),patch.object(evaluate,"source_predictability",return_value={"scope":"fixture"}),redirect_stdout(io.StringIO()):
            cls.selection=evaluate.select(cls.dataset,cls.run_dir,cls.lock)
        cls.reads=reads

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def test_selection_never_reads_holdouts(self):
        self.assertEqual(set(self.reads),{"train","validation","validation_historical"})

    def test_all_four_lightweight_candidates(self):
        self.assertEqual(set(self.selection["candidates"]),set(CANDIDATES))

    def test_thresholds_use_later_validation_only(self):
        for c in self.selection["candidates"].values():
            self.assertEqual(c["threshold_origin"],"SpaPhish 2023 only")

    def test_selection_starts_inactive_research(self):
        for c in self.selection["candidates"].values():
            self.assertFalse(c["active"]);self.assertEqual(c["status"],"RESEARCH")

    def test_lock_verifies(self):
        evaluate.verify_lock(self.dataset,self.run_dir,self.lock)

    def test_changed_gate_rejected(self):
        with patch.dict(evaluate.EXTRA_POLICY,{"external_min_recall":.5}),self.assertRaises(ValueError):
            evaluate.verify_lock(self.dataset,self.run_dir,self.lock)

    def test_changed_code_rejected(self):
        with patch.object(evaluate,"code_hashes",return_value={}),self.assertRaises(ValueError):
            evaluate.verify_lock(self.dataset,self.run_dir,self.lock)

    def test_lock_tampering_rejected(self):
        p=self.base/"tampered.json";p.write_bytes(self.lock.read_bytes()+b" ")
        with self.assertRaises(ValueError):evaluate.verify_lock(self.dataset,self.run_dir,p)

    def test_selection_cannot_overwrite(self):
        with self.assertRaises(FileExistsError):evaluate.select(self.dataset,self.run_dir,self.lock)

    def test_model_binary_tampering_rejected(self):
        name=CANDIDATES[0];p=self.run_dir/(name+".joblib");original=p.read_bytes()
        try:
            p.write_bytes(original+b"corruption")
            with self.assertRaises(ValueError):evaluate.verify_lock(self.dataset,self.run_dir,self.lock)
        finally:p.write_bytes(original)

    def test_single_use_marker_prevents_reopening(self):
        marker=Path(str(self.lock)+".test-opened");marker.write_text("previously opened")
        try:
            with self.assertRaises(FileExistsError):
                evaluate.finalize(self.dataset,self.run_dir,self.lock,self.base/"models",self.base/"final.json")
        finally:marker.unlink()

    def test_complete_finalize_writes_inactive_metadata_without_switching_choice(self):
        import shutil
        with TemporaryDirectory() as directory:
            base=Path(directory)
            dataset=base/"data";run=base/"run";lock=base/"selection.json"
            shutil.copytree(self.dataset,dataset);shutil.copytree(self.run_dir,run);shutil.copyfile(self.lock,lock)
            with redirect_stdout(io.StringIO()):
                result=evaluate.finalize(dataset,run,lock,base/"models",base/"final.json")
            self.assertEqual(result["selected_model"],self.selection["selected_model"])
            for name in CANDIDATES:
                meta=json.loads((base/"models"/name/"metadata.json").read_text())
                self.assertFalse(meta["active"])
                self.assertEqual(meta["status"],"UNVALIDATED")
            self.assertTrue(Path(str(lock)+".test-opened").exists())
            with self.assertRaises(FileExistsError):
                evaluate.finalize(dataset,run,lock,base/"another-model",base/"another-final.json")

    def test_loader_resolves_from_different_working_directory(self):
        import os
        before=Path.cwd()
        try:
            os.chdir(self.base)
            self.assertEqual(evaluate.verify_legacy(),evaluate.LEGACY_HASHES)
        finally:os.chdir(before)

